import type { CalculationInput, LinkBudget, LatLon } from './types'

/** Звено цепочки: линия между двумя узлами (пока без расчёта). */
export interface MeshLink {
  id: string
  /** Узел-передатчик звена */
  from: LatLon
  /** Узел-приёмник звена */
  to: LatLon
  /** Входные данные линии (прямая/обратная, частоты) — заполняется на этапе 2.4 */
  input?: CalculationInput
  /** Бюджет звена — заполняется на этапе 2.4 */
  budget?: LinkBudget
}

/** Цепочка ретрансляций A→Б→В… (mesh-сеть из последовательных звеньев). */
export interface MeshChain {
  id: string
  /** Человекочитаемое имя цепочки */
  name?: string
  links: MeshLink[]
}

